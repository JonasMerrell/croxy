"""Write docs/manufacturing.md from the build outputs (out/mfg.json + out/assembly-info.json).

    python3 cad/mfg_doc.py [out_dir]
"""
import collections, json, os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.abspath(sys.argv[1] if len(sys.argv) > 1 else os.path.join(HERE, "..", "out"))
mfg = json.load(open(os.path.join(OUT, "mfg.json")))
info = json.load(open(os.path.join(OUT, "assembly-info.json")))
bom = {b["part"]: b for b in info["bom"]}

# what each standard part is used for, from the instance names ("fx <label> <size> <tag>")
use = collections.defaultdict(collections.Counter)
for i in info["instances"]:
    n = i["name"] or ""
    if n.startswith("fx "):
        lab = re.sub(r"\s(M\d+(\.\d+)?|Ø\d+)\b.*$", "", n[3:]).strip()
        use[i["part"]["name"]][lab] += 1

GROUPS = [("Milled on the 3-axis mill", lambda m: m == "mill"),
          ("Send Cut Send: laser cut (and bent)", lambda m: m.startswith("SCS")),
          ("Waterjet, then milled", lambda m: m.startswith("waterjet")),
          ("3D printed, no supports", lambda m: m == "print"),
          ("Bought, then cut / drilled / faced", lambda m: m.startswith("buy +")),
          ("Cut from board", lambda m: m == "cut"),
          ("Bought as is", lambda m: m == "buy")]

L = ["# CroXY manufacturing sheet", "",
     "Generated by `cad/mfg_doc.py` from the rCAD build. Each part lists how it is made, from what, and the setups or print",
     "orientation. Rules: CNC parts are 3-axis mill only (each setup is one face up); printed parts print without supports",
     "(PPS-CF in the hot zone, PET-CF outside); sheet parts come from Send Cut Send with their holes; no welding, no lathe.", ""]
for title, test in GROUPS:
    rows = [(n, v) for n, v in sorted(mfg.items()) if test(v["method"])]
    if not rows:
        continue
    L += [f"## {title}", "", "| Part | Qty | Material | Mass each | How |", "|---|---:|---|---:|---|"]
    for n, v in rows:
        b = bom.get(n, {})
        q = b.get("qty", "")
        mass = f"{b['mass_g']:.0f} g" if b.get("mass_g") else ""
        L.append(f"| {n} | {q} | {v['material'] or '-'} | {mass} | {v['notes']} |")
    L.append("")

L += ["## Fasteners and standard parts", "", "| Part | Qty | Used for |", "|---|---:|---|"]
std = [b for b in info["bom"] if b["part"] not in mfg and (b["part"].startswith(("ISO", "Shaft", "Bearing")) or b["part"] in use)]
for b in sorted(std, key=lambda b: b["part"]):
    u = ", ".join(f"{k} x{c}" for k, c in use[b["part"]].most_common()) or "-"
    L.append(f"| {b['part']} | {b['qty']} | {u} |")
L.append("")
total = sum(b["qty"] for b in std)
L += [f"{total} standard parts in all. Shafts named `Shaft Ø5` / `Shaft Ø8` that are used as threaded rod are cut from",
      "M5 / M8 threaded rod. Tapped holes are modelled at the nominal diameter.", ""]

rest = [b for b in info["bom"] if b["part"] not in mfg and b not in std]
if rest:
    L += ["## Other bought parts and stand-ins", "", "| Part | Qty |", "|---|---:|"]
    L += [f"| {b['part']} | {b['qty']} |" for b in sorted(rest, key=lambda b: b["part"])]
    L.append("")

path = os.path.join(HERE, "..", "docs", "manufacturing.md")
open(path, "w").write("\n".join(L))
print("wrote", os.path.relpath(path), len(mfg), "made parts,", total, "standard parts")
